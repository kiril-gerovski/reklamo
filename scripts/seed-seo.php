$reklamo_set    = 0;
$reklamo_titles = in_array( 'titles', (array) ( $args ?? array() ), true );

foreach ( $reklamo_pages as $reklamo_key => $reklamo_fields ) {
	if ( 'front' === $reklamo_key ) {
		$reklamo_id = (int) get_option( 'page_on_front' );
	} elseif ( 'shop' === $reklamo_key ) {
		$reklamo_id = function_exists( 'wc_get_page_id' ) ? (int) wc_get_page_id( 'shop' ) : 0;
	} else {
		$reklamo_id = (int) get_page_by_path( $reklamo_key )?->ID;
	}
	if ( $reklamo_id <= 0 ) {
		continue;
	}
	foreach ( $reklamo_fields as $reklamo_field => $reklamo_value ) {
		if ( $reklamo_titles && 'text' === $reklamo_field ) {
			continue;
		}
		if ( '' === (string) get_post_meta( $reklamo_id, '_reklamo_seo_' . $reklamo_field, true ) ) {
			update_post_meta( $reklamo_id, '_reklamo_seo_' . $reklamo_field, wp_slash( $reklamo_value ) );
			++$reklamo_set;
		}
	}
}

foreach ( $reklamo_cats as $reklamo_slug => $reklamo_fields ) {
	$reklamo_term = get_term_by( 'slug', $reklamo_slug, 'product_cat' );
	if ( ! $reklamo_term ) {
		continue;
	}
	if ( ! $reklamo_titles && '' === trim( $reklamo_term->description ) ) {
		wp_update_term( $reklamo_term->term_id, 'product_cat', array( 'description' => $reklamo_fields['description'] ) );
		++$reklamo_set;
	}
	foreach ( $reklamo_titles ? array( 'title' ) : array( 'title', 'text' ) as $reklamo_field ) {
		if ( '' === (string) get_term_meta( $reklamo_term->term_id, '_reklamo_seo_' . $reklamo_field, true ) ) {
			update_term_meta( $reklamo_term->term_id, '_reklamo_seo_' . $reklamo_field, wp_slash( $reklamo_fields[ $reklamo_field ] ) );
			++$reklamo_set;
		}
	}
}

echo '  search wording: ' . (int) $reklamo_set . " empty fields filled\n";
